"""HA Package Generator tool.

Parses user registry configurations, resolves entities via adapters, and outputs
a consolidated, production-ready Home Assistant Package YAML.
"""

import json
from pathlib import Path
from typing import Dict, Any, List

try:
    import yaml
    HAS_YAML = True
except ImportError:
    HAS_YAML = False

from src.registry.validator import RegistryValidator
from src.registry.models import RegistryData, DeviceConfig
from src.adapters.factory import AdapterFactory
from src.adapters.base import ResolvedEntities


class PackageGenerator:
    """Generates Home Assistant Package YAML from validated registry."""

    def __init__(self, registry_dir: Path, output_file: Path) -> None:
        """Initialize generator with registry directory and target output package path."""
        self.registry_dir = Path(registry_dir)
        self.output_file = Path(output_file)
        self.validator = RegistryValidator(
            registry_dir=self.registry_dir,
            available_adapters=AdapterFactory.available_adapters(),
        )

    def generate(self) -> Path:
        """Run validation and compile HA package YAML file.

        Returns:
            Path to generated package file.
        """
        registry = self.validator.load_and_validate()
        resolved_devices = self._resolve_devices(registry.devices)

        package_dict = {
            "homeassistant": {
                "customize": self._build_customizations(registry, resolved_devices),
            },
            "input_boolean": {
                "riego_engine_enabled": {
                    "name": "Irrigation Engine Active State",
                    "icon": "mdi:water-pump",
                    "initial": True,
                },
                "riego_rain_skip": {
                    "name": "Rain Skip Active Flag",
                    "icon": "mdi:weather-rainy",
                    "initial": False,
                },
            },
            "input_number": {
                "riego_watchdog_timeout": {
                    "name": "Watchdog Safety Cutoff (Minutes)",
                    "min": 5,
                    "max": 120,
                    "step": 1,
                    "initial": registry.settings.watchdog_timeout,
                    "unit_of_measurement": "min",
                    "icon": "mdi:timer-alert",
                },
                "riego_max_duration": {
                    "name": "Maximum Irrigation Limit (Minutes)",
                    "min": 10,
                    "max": 360,
                    "step": 5,
                    "initial": registry.settings.max_irrigation_minutes,
                    "unit_of_measurement": "min",
                    "icon": "mdi:clock-end",
                },
            },
        }

        self.output_file.parent.mkdir(parents=True, exist_ok=True)
        with open(self.output_file, "w", encoding="utf-8") as f:
            if HAS_YAML:
                yaml.dump(package_dict, f, sort_keys=False, allow_unicode=True)
            else:
                f.write("# Generated by HA Irrigation Engine Generator\n")
                f.write(json.dumps(package_dict, indent=2))

        return self.output_file

    def _resolve_devices(self, devices: List[DeviceConfig]) -> Dict[str, ResolvedEntities]:
        """Resolve entities for all devices using AdapterFactory."""
        resolved: Dict[str, ResolvedEntities] = {}
        for dev in devices:
            adapter = AdapterFactory.get_adapter(dev.adapter)
            resolved[dev.id] = adapter.resolve_entities(dev.switch)
        return resolved

    def _build_customizations(
        self, registry: RegistryData, resolved_devices: Dict[str, ResolvedEntities]
    ) -> Dict[str, Dict[str, Any]]:
        """Build HA customize dictionary with device metadata."""
        customizations: Dict[str, Dict[str, Any]] = {}
        for dev in registry.devices:
            resolved = resolved_devices[dev.id]
            customizations[resolved.switch] = {
                "friendly_name": f"Irrigation Valve — {dev.name}",
                "device_id": dev.id,
                "adapter": dev.adapter,
                "battery_entity": resolved.battery,
                "flow_entity": resolved.flow,
                "duration_entity": resolved.duration,
                "volume_entity": resolved.volume,
                "status_entity": resolved.status,
                "work_state_entity": resolved.work_state,
            }
        return customizations


def main() -> None:
    """CLI execution entrypoint."""
    project_root = Path(__file__).resolve().parent.parent.parent
    registry_path = project_root / "registry"
    output_path = project_root / "packages" / "ha_irrigation_engine.yaml"

    generator = PackageGenerator(registry_dir=registry_path, output_file=output_path)
    out = generator.generate()
    print(f"Successfully generated Home Assistant package: {out}")


if __name__ == "__main__":
    main()
